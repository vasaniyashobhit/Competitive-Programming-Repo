#include <bits/stdc++.h>
using namespace std;

using ll = long long;

void solve() {
    int x,y,r; cin>>x>>y>>r;
    cout<<x<<" "<<y+r<<endl;
    return;
}

int main() {
    // Fast I/O
    ios_base::sync_with_stdio(false);
    cin.tie(NULL);

    int t; cin >> t;
    while (t--) solve();

    return 0;
}